# Benchmarks for the "market mood" check
MARKET_BENCHMARKS = {"stocks": "SPY", "eu_stocks": "^GDAXI", "crypto": "BTC-USD"}
FX_TICKER = "EURUSD=X"   # how many USD one EUR buys


def all_stocks():
    return list(dict.fromkeys(US_STOCKS + EU_STOCKS))


def all_crypto():
    return list(dict.fromkeys(CRYPTO))


def asset_class(ticker):
    if ticker.endswith("-USD"):
        return "crypto"
    if ticker.endswith(".DE"):
        return "eu_stock"
    return "us_stock"


def currency(ticker):
    return "EUR" if ticker.endswith(".DE") else "USD"


def pretty(ticker):
    """BTC-USD -> BTC, PEPE24478-USD -> PEPE, SAP.DE -> SAP"""
    t = ticker.replace("-USD", "").replace(".DE", "")
    return "".join(ch for ch in t if not ch.isdigit()) or t
